"""Export the restyled eggs (<name>_NEW objects) as ONE FBX for Studio's Import 3D.

Each egg is matched to its Studio MeshPart by name and size (studio_eggs.txt, written from
ReplicatedStorage.Assets.Eggs.GoldEggs) and named  EGG_<MeshId>  so Studio can find every part
that uses that mesh in all five egg folders, however the parts are named.
The mesh keeps Roblox axes in its own data (bake_space_transform), because Studio swaps the mesh
into the existing parts with ApplyMesh and those parts must not be turned.

blender -b eggs_all.blend -P eggs_export.py -- <studio_eggs.txt> <out.fbx> <manifest.lua>
"""
import bpy, sys, re, math
from mathutils import Vector, Matrix

lst, fbx_out, manifest = sys.argv[sys.argv.index("--") + 1:][:3]
studio = []
for item in open(lst).read().strip().split(","):
    name, mid, size = item.split("=")
    studio.append(dict(name=name, id=mid, size=[float(x) for x in size.split("/")], used=False))

news = sorted((o for o in bpy.data.objects if o.name.endswith("_NEW") and o.name.lower().startswith("egg")), key=lambda o: o.name)
out, lines, unmatched = [], [], []
for i, o in enumerate(news):
    src = bpy.data.objects[o.name[:-4]]
    key = re.sub(r"\d+$", "", src.name[3:])                       # 'Eggpolarbear2' -> 'polarbear'
    d = src.dimensions                                           # Blender x, y, z = Roblox x, z, y
    cands = [s for s in studio if not s["used"] and re.sub(r"[^a-z0-9]", "", s["name"].lower()) == key]
    cands.sort(key=lambda s: abs(s["size"][0] - d.x) + abs(s["size"][1] - d.z) + abs(s["size"][2] - d.y))
    if not cands or abs(cands[0]["size"][0] - d.x) + abs(cands[0]["size"][1] - d.z) + abs(cands[0]["size"][2] - d.y) > 0.05:
        unmatched.append(src.name); continue
    s = cands[0]; s["used"] = True
    c = o.copy(); c.data = o.data.copy(); c.name = "EGG_" + s["id"]; c.data.name = c.name
    bpy.context.scene.collection.objects.link(c)
    me = c.data
    cs = [v.co for v in me.vertices]
    mn = Vector((min(p.x for p in cs), min(p.y for p in cs), min(p.z for p in cs)))
    mx = Vector((max(p.x for p in cs), max(p.y for p in cs), max(p.z for p in cs)))
    me.transform(Matrix.Translation(-(mn + mx) / 2))             # origin = box centre, like a MeshPart
    size = mx - mn
    # which way the egg leans: average corner position, as a fraction of its size, in ROBLOX mesh
    # axes (x, up, -y). Studio reads the imported mesh back and compares, so a turned mesh is caught.
    lc = [me.vertices[l.vertex_index].co for l in me.loops]
    av = sum(lc, Vector()) / len(lc)
    lean = (av.x / size.x, av.z / size.z, -av.y / size.y)
    # The first export came into Studio with every mesh turned half a turn about the vertical axis
    # (measured: mesh x = -Blender x, mesh z = +Blender y; the eggs' own meshes have x = +x, z = -y).
    # So the mesh data is pre-turned half a turn here, which lands it the right way round.
    me.transform(Matrix.Rotation(math.pi, 4, 'Z'))
    c.matrix_world = Matrix.Translation(((i % 14) * 30.0, (i // 14) * 30.0, 10.0))
    lines.append(f'\t["{s["id"]}"] = {{ name = "{s["name"]}", size = Vector3.new({size.x:.4f}, {size.z:.4f}, {size.y:.4f}), '
                 f'old = Vector3.new({s["size"][0]}, {s["size"][1]}, {s["size"][2]}), '
                 f'lean = Vector3.new({lean[0]:.4f}, {lean[1]:.4f}, {lean[2]:.4f}) }},')
    out.append(c)
missing = [s["name"] + "=" + s["id"] for s in studio if not s["used"]]
print("MATCHED", len(out), "UNMATCHED_OBJ", unmatched, "MISSING_FROM_EXPORT", missing)

for mname, loc in (("SOA_AxisO", (0, 0, 0)), ("SOA_AxisUp", (0, 0, 3)), ("SOA_AxisFwd", (0, 3, 0))):
    bpy.ops.mesh.primitive_cube_add(size=0.2, location=loc)
    mk = bpy.context.active_object; mk.name = mname; out.append(mk)
open(manifest, "w").write("-- generated by eggs_export.py: [MeshId] = name, new size and old size in studs (Roblox axes)\nreturn {\n"
                          + "\n".join(lines) + "\n}\n")
bpy.ops.object.select_all(action='DESELECT')
for o in out: o.select_set(True)
bpy.context.view_layer.objects.active = out[0]
bpy.ops.export_scene.fbx(filepath=fbx_out, use_selection=True, object_types={'MESH'}, apply_unit_scale=True,
                         mesh_smooth_type='FACE', bake_space_transform=True, axis_forward='-Z', axis_up='Y')
print("FBX", fbx_out, len(out), "objects, tris", sum(sum(len(p.vertices) - 2 for p in o.data.polygons) for o in out))
